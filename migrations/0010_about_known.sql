Gurdwara Sri Guru Arjan Dev Ji Sahib stands, according to Punjab Kosh, outside the village on the road toward Jagdev Kalan. The entry describes white marble, Khanda emblems on the domes, a Nishan Sahib of about 105 feet, a small library, and twelve rooms for visitors. This archive has no photograph and no foundation date.

The government primary school, GPS Mallu Nangal, is recorded as opening in 1925. Directories also list a government high school and a private primary, Sri Guru Arjun Dev Model School.

Raja Sansi, about five kilometres away, is the nearest town and the post office for PIN 143101. Neighbouring villages named in directories are Adliwala, Loharka Kalan, Ranewali, Jagdev Kalan, and Loharka Khurd.

A drawn map of ponds, shamlat land, and streets has not been compiled.$about$

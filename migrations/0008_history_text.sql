  body = $hist$## 1. Introduction

Mallu Nangal (ਮੱਲੂ ਨੰਗਲ), also spelled Malu Nangal in official records, is a village in Amritsar district, Punjab, in the Majha region. The village is associated with a local historical tradition connecting Sri Guru Arjan Dev Ji, the fifth Sikh Guru, with Bhai Mallu Ji, whose name is traditionally linked to the village’s present name.

The principal written accounts of this tradition appear in Punjab Kosh, published by the Language Department of Punjab, and in an online record of Gurdwara Sri Guru Arjan Dev Ji Sahib at Mallu Nangal.

These accounts preserve the village’s religious heritage but differ on the earlier name of the settlement and the events surrounding its establishment. The story of the village’s origin is therefore a traditional historical account, not a fully verified chronology.

## 2. The traditional connection with Sri Guru Arjan Dev Ji

According to Punjab Kosh, Sri Guru Arjan Dev Ji visited the area while travelling towards Guru Ke Bagh. During this journey, Guru Sahib is said to have stopped briefly and requested water.

The account relates that a Sikh attendant drew water from a nearby well in an earthen vessel. A Pathan from the settlement broke the vessel, leaving Guru Sahib without water.

The account attributes the following words to Guru Sahib:

“ਜਾਣਗੇ ਲਿੱਲੇ, ਆਉਣਗੇ ਗਿੱਲੇ.”

The traditional narrative associates these words with the subsequent departure of the earlier inhabitants and the emergence of the settlement known as Mallu Nangal.

A separate account published by HistoricalGurudwaras.com also describes Guru Arjan Dev Ji’s visit while travelling towards Guru Ke Bagh. It adds that Raja Hari Sen of Suket Mandi accompanied Guru Sahib.

Although both accounts describe an incident involving water and a broken vessel, they differ in other details. The available sources do not establish the exact date of the visit, and they do not independently verify every element of the story.

## 3. Bhai Mallu Ji and the origin of the village’s name

Bhai Mallu Ji occupies an important place in the traditional history of Mallu Nangal. The two available accounts describe his role differently.

According to Punjab Kosh, a Sikh named Mallu Gill was grazing buffaloes outside the settlement. Upon learning about the incident involving Guru Sahib, he gathered approximately 20–25 Sikhs and attacked the Pathans during the night. The account states that the Pathans subsequently left the settlement, and that Guru Sahib later named the village Mallu Nangal in recognition of Mallu’s actions.

The separate Gurdwara account identifies Bhai Malu Ji as a resident of Jagdev Kalan. It states that he later attacked and destroyed the earlier settlement and established a new village that became known as Malu Nangal.

Both accounts associate the village’s name with Mallu or Malu. They differ in their descriptions of the earlier settlement and in the circumstances in which the new village was established.

The available sources do not independently establish Bhai Mallu Ji’s birth date, family lineage, father’s name, or the precise date of the settlement’s foundation. Those details remain open to further investigation.

## 4. Gurdwara Sri Guru Arjan Dev Ji Sahib

Gurdwara Sri Guru Arjan Dev Ji Sahib is the religious landmark associated with the traditional account of Guru Sahib’s visit to Mallu Nangal.

The Punjab Kosh entry describes the Gurdwara as standing outside the village, on the road towards Jagdev Kalan. It records a white-marble building, domes bearing Khanda symbols, a Nishan Sahib approximately 105 feet high, a library relating to Sikh history, and twelve rooms for visitors.

The same account mentions the observance of Gurpurabs, Sangrand gatherings, and the serving of langar.

These details document the Gurdwara’s religious and community significance as described in the published entry. The exact date of its original construction, and the earliest surviving documentary record of the shrine, have not been established by the sources examined.

The Gurdwara and its management committee may hold further information about its development, its historical traditions, and its past custodians.$hist$
